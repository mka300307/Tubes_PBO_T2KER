    private void loadProduk() {

        try {

            listProduk = controller.getProdukAktif();

            cmbProduk.removeAllItems();

            for (ProdukItem p : listProduk) {
                cmbProduk.addItem(p.getNama());
            }

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );

        }

    }
    
    private void refreshTable() {

        model.setRowCount(0);

        for (DetailTransaksiItem item : listSementara) {

            model.addRow(new Object[]{
                item.getNamaProduk(),
                item.getHargaSatuan(),
                item.getJumlah(),
                item.getSubtotal()
            });

        }

        double total = controller.hitungTotal(listSementara);

        tfTotalBelanja.setText(
                String.format("%.0f", total)
        );
    }
    
    private void clearForm() {

        listSementara.clear();
        listIdProduk.clear();

        model.setRowCount(0);

        tfJumlah.setText("");
        tfTotalBelanja.setText("");
        tfUangBayar.setText("");

        if (cmbProduk.getItemCount() > 0) {
            cmbProduk.setSelectedIndex(0);
        }
    }
    
