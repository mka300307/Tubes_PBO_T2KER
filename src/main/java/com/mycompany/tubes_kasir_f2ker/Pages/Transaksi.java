    private void btnSelesaiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSelesaiActionPerformed
        try {

            if (listSementara.isEmpty()) {
                throw new Exception("Belum ada item transaksi!");
            }

            double total =
                    controller.hitungTotal(listSementara);

            if (tfUangBayar.getText().trim().isEmpty()) {
                throw new Exception("Uang bayar belum diisi!");
            }

            double uangBayar =
                    Double.parseDouble(
                            tfUangBayar.getText()
                    );

            double kembalian =
                    controller.hitungKembalian(
                            uangBayar,
                            total
                    );

            int idTransaksi =
                    controller.simpanTransaksi(
                            idUserLogin,
                            total,
                            listSementara
                    );

            JOptionPane.showMessageDialog(
                    this,
                    """
                    Transaksi berhasil!

                    ID Transaksi : """ + idTransaksi +
                    "\nTotal Belanja : Rp " + String.format("%,.0f", total) +
                    "\nUang Bayar : Rp " + String.format("%,.0f", uangBayar) +
                    "\nKembalian : Rp " + String.format("%,.0f", kembalian)
            );

            clearForm();

            loadProduk();

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );

        }
    }//GEN-LAST:event_btnSelesaiActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {

            if (cmbProduk.getSelectedIndex() == -1) {
                throw new Exception("Pilih produk terlebih dahulu!");
            }

            if (tfJumlah.getText().trim().isEmpty()) {
                throw new Exception("Jumlah belum diisi!");
            }

            ProdukItem produk =
                    listProduk.get(cmbProduk.getSelectedIndex());

            int jumlah =
                    Integer.parseInt(tfJumlah.getText());

            controller.tambahItem(
                    listSementara,
                    listIdProduk,
                    produk,
                    jumlah
            );

            refreshTable();

            tfJumlah.setText("");

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    this,
                    e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );

        }
    }//GEN-LAST:event_jButton1ActionPerformed

