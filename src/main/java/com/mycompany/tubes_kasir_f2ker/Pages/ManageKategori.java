    private void klikRow() {
        int row = tblKategori.getSelectedRow();
        if (row == -1) return;

        String namaKategori = tblKategori.getValueAt(row, 0).toString();

        try {
            selectedId = kategoriController.getIdByNama(namaKategori);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        tfKategori.setText(namaKategori);
    }
    
    public void loadDataKategori(String keyword){
        try {
            List<KategoriItem> list = kategoriController.searchKategori(keyword);
            model.setRowCount(0);
            for (KategoriItem kategoriItem : list) {
                model.addRow(new Object[]{kategoriItem.getNama()});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    
