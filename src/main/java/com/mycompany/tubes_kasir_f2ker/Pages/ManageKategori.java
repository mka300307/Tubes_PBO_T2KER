    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        KategoriItem input = getFormInput();
        if (input == null) return;

        try {
            kategoriController.addKategori(input);
            JOptionPane.showMessageDialog(this, "Kategori berhasil ditambahkan!", "Sukses",
                JOptionPane.INFORMATION_MESSAGE);
            clearForm();
            loadDataKategori("");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        if (selectedId == -1) {
            JOptionPane.showMessageDialog(this, "Pilih Kategori dari tabel terlebih dahulu!",
                "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        KategoriItem kategori = getFormInput();
        if(kategori == null) return;
        kategori.setId(selectedId);
        
        try {
            kategoriController.updateKategori(kategori);
            JOptionPane.showMessageDialog(this, "Kategori berhasil diupdate!", "Sukses",
                JOptionPane.INFORMATION_MESSAGE);
            clearForm();
            loadDataKategori("");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
        
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if (selectedId == -1) {
            JOptionPane.showMessageDialog(this, "Pilih kategori dari tabel terlebih dahulu!",
                "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        int konfirmasi = JOptionPane.showConfirmDialog(this,
            "Yakin ingin menghapus kategori " + tfKategori.getText() + "?",
            "Konfirmasi Hapus", JOptionPane.YES_NO_OPTION, JOptionPane.WARNING_MESSAGE);
        if(konfirmasi != JOptionPane.YES_OPTION) return;
        
        try {
            kategoriController.deleteKategori(selectedId);
            JOptionPane.showMessageDialog(this, "Kategori berhasil dihapus!", "Sukses",
                JOptionPane.INFORMATION_MESSAGE);
            clearForm();
            loadDataKategori("");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

